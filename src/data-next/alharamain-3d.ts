function parseRing(s: string): [number, number][] {
  const pts = s.split('#').map((p) => {
    const [lng, lat] = p.split(',').map(Number);
    return [lng, lat] as [number, number];
  });
  if (pts.length && (pts[0][0] !== pts[pts.length - 1][0] || pts[0][1] !== pts[pts.length - 1][1])) pts.push(pts[0]);
  return pts;
}

let cachedZones: FeatureCollection<Polygon, AlharamainZoneProps> | null = null;

/** GeoJSON FeatureCollection for the `alharamain-zones` source and `alharamain-3d-buildings` layer. */
export function alharamainZones(): FeatureCollection<Polygon, AlharamainZoneProps> {
  if (cachedZones) return cachedZones;
  const features: Feature<Polygon, AlharamainZoneProps>[] = RAW_ZONES.map(([id, floor_id, venue_id, category_id, category_color, extrusion_height, ring]) => ({
    type: 'Feature',
    id,
    geometry: { type: 'Polygon', coordinates: [parseRing(ring)] },
    properties: { id, floor_id, venue_id, category_id, category_color, extrusion_height, extrusion_base: 0 },
  }));
  return (cachedZones = { type: 'FeatureCollection', features });
}
